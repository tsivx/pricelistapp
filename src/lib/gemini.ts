// ——— RESPONSE SCHEMA: attrs = динамический массив name/value + markup_breakdown ———
export const RESPONSE_SCHEMA = {
  type: 'ARRAY',
  items: {
    type: 'OBJECT',
    properties: {
      brand: { type: 'STRING' },
      category: { type: 'STRING' },
      model: { type: 'STRING' },
      name: { type: 'STRING' },
      original_price: { type: 'NUMBER' },
      markup_applied: { type: 'NUMBER' },
      final_price: { type: 'NUMBER' },
      markup_breakdown: { type: 'STRING' },
      attrs: {
        type: 'ARRAY',
        items: {
          type: 'OBJECT',
          properties: {
            name: { type: 'STRING' },
            value: { type: 'STRING' },
          },
          required: ['name', 'value'],
        },
      },
    },
    required: ['brand', 'category', 'model', 'name', 'original_price', 'markup_applied', 'final_price', 'markup_breakdown', 'attrs'],
  },
} as const

export function buildUserPrompt(rules: string, rounding: string, raw: string, extra: string = ''): string {
  const parts: string[] = []
  parts.push('Правила наценки:')
  parts.push(rules?.trim() ? rules.trim() : '(дополнительных текстовых правил нет)')
  if (rounding) parts.push(`Округление: до ${rounding} в большую сторону (ceil до кратного ${rounding}) в пользу магазина. ВАЖНО: округляется ТОЛЬКО итоговая цена ПОСЛЕ сложения всех наценок (цену без округления вычислить, затем один раз округлить вверх до кратного ${rounding}).`)
  else parts.push('Округление: не применять (если в правилах выше не указано иное).')
  parts.push('')
  if (extra?.trim()) {
    parts.push('Дополнительные условия:')
    parts.push(extra.trim())
    parts.push('')
  }
  parts.push('Прайс-лист:')
  parts.push(raw)
  parts.push('')
  parts.push(
    'Верни JSON-массив по схеме: у каждого товара свой набор атрибутов attrs (никакого фиксированного перечня — только то, что реально есть). Для каждого товара заполни markup_breakdown по формату из инструкции (только слагаемые наценки + округление последним). Порядок: исходная + все наценки = цена_без_округления, затем ОДИН РАЗ округлить вверх => final_price. Удали полные дубликаты, но аномальные цены не исправляй.',
  )
  return parts.join('\n')
}

export async function callGemini(
  apiKey: string,
  model: string,
  userPrompt: string,
): Promise<PricelistItem[]> {
  const modelId = model.replace(/^models\//, '')
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(modelId)}:generateContent?key=${encodeURIComponent(apiKey)}`

  const body = {
    systemInstruction: { parts: [{ text: SYSTEM_INSTRUCTION }] },
    contents: [{ role: 'user', parts: [{ text: userPrompt }] }],
    generationConfig: {
      temperature: 0.1,
      responseMimeType: 'application/json',
      responseSchema: RESPONSE_SCHEMA,
    },
  }

  const res = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  })

  const data = await res.json().catch(() => null)
  if (!res.ok) {
    const msg = data?.error?.message || `HTTP ${res.status}`
    throw new Error(`Gemini API: ${msg}`)
  }
  const text: string = data?.candidates?.[0]?.content?.parts?.map((p: { text: string }) => p.text).join('') ?? ''
  if (!text) throw new Error('Пустой ответ от Gemini.')
  let parsed: unknown
  try {
    parsed = JSON.parse(text)
  } catch {
    throw new Error('Gemini вернул невалидный JSON:\n' + text.slice(0, 1000))
  }
  if (!Array.isArray(parsed)) throw new Error('Ожидался JSON-массив.')
  return parsed as PricelistItem[]
}
